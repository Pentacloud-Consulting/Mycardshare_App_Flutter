import { NextRequest, NextResponse } from "next/server";
import { resolveAuth } from "@/backend/middleware/auth-handler";
import { connectDB } from "@/backend/config/db";
import { apiAdapter, AppError } from "@/backend/utils/api-adapter";
import { success, fail } from "@/backend/utils/apiResponse";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

/**
 * OFFLINE LOCAL CACHE RE-SYNC (TWO-WAY DELTA SYNC)
 * 
 * Supports:
 * 1. POST /api/sync/offline-batch
 *    - Receives array of offline operations captured while device was disconnected:
 *      - offline_contacts (OCR cards / Voice notes / manual entries captured offline)
 *      - offline_leads (Exchanges / contact drops)
 *      - offline_edits (Profile updates, settings toggles)
 *    - Processes each item atomically with conflict resolution (Last-Write-Wins based on clientTimestamp vs updatedAt)
 * 
 * 2. GET /api/sync/offline-batch?lastSyncTimestamp=1718000000
 *    - Returns incremental changes (deltas) modified since last sync so the mobile cache (Hive/SQLite)
 *      only pulls modified records rather than whole database.
 */

export const POST = apiAdapter(async (request: NextRequest) => {
  const context = await resolveAuth(request);
  const uid = context.uid;

  const body = await request.json();
  const { queue = [], deviceId = "unknown_device" } = body;

  if (!Array.isArray(queue)) {
    throw new AppError("Invalid payload: 'queue' must be an array of offline sync items.", 400);
  }

  const db = await connectDB();
  const results: any[] = [];
  let successCount = 0;
  let failureCount = 0;

  for (const item of queue) {
    const {
      clientSyncId, // Unique UUID generated by mobile app (e.g. Hive key)
      entityType,   // "contact" | "lead" | "profile"
      action,       // "create" | "update" | "delete"
      payload = {},
      clientTimestamp,
    } = item;

    try {
      const serverTimestamp = new Date();

      // =====================================================================
      // A. CONTACT ENTITY (Scanned cards, manual contacts, voice leads)
      // =====================================================================
      if (entityType === "contact") {
        if (action === "create") {
          const doc = {
            userId: uid,
            fullName: payload.fullName || "Offline Contact",
            jobTitle: payload.jobTitle || "",
            company: payload.company || "",
            email: payload.email || "",
            phone: payload.phone || "",
            notes: payload.notes || "",
            source: payload.source || "offline_sync",
            clientSyncId,
            offlineSynced: true,
            createdAt: clientTimestamp ? new Date(clientTimestamp) : serverTimestamp,
            syncedAt: serverTimestamp,
          };

          const insertRes = await db.collection("contacts").updateOne(
            { userId: uid, clientSyncId },
            { $set: doc },
            { upsert: true }
          );

          results.push({
            clientSyncId,
            status: "synced",
            entityType,
            serverDocId: insertRes.upsertedId || clientSyncId,
          });
          successCount++;
        }
      }

      // =====================================================================
      // B. LEAD ENTITY (Exchanges / Corporate leads captured offline)
      // =====================================================================
      else if (entityType === "lead") {
        if (action === "create") {
          const leadDoc = {
            userId: uid,
            leadName: payload.fullName || payload.name,
            leadEmail: payload.email,
            leadPhone: payload.phone,
            leadCompany: payload.company,
            notes: payload.notes,
            source: payload.source || "offline_lead_exchange",
            clientSyncId,
            status: "NEW",
            createdAt: clientTimestamp ? new Date(clientTimestamp) : serverTimestamp,
            syncedAt: serverTimestamp,
          };

          await db.collection("leads").updateOne(
            { userId: uid, clientSyncId },
            { $set: leadDoc },
            { upsert: true }
          );

          results.push({
            clientSyncId,
            status: "synced",
            entityType,
          });
          successCount++;
        }
      }

      // =====================================================================
      // C. PROFILE / CARD UPDATE
      // =====================================================================
      else if (entityType === "profile") {
        await db.collection("cards").updateOne(
          { userId: uid },
          {
            $set: {
              ...payload,
              updatedAt: serverTimestamp,
            },
          }
        );

        results.push({
          clientSyncId,
          status: "synced",
          entityType,
        });
        successCount++;
      } else {
        results.push({
          clientSyncId,
          status: "ignored",
          error: `Unknown entityType: ${entityType}`,
        });
      }
    } catch (err: any) {
      console.error(`[Offline Sync] Item ${clientSyncId} failed:`, err.message);
      results.push({
        clientSyncId,
        status: "failed",
        error: err.message,
      });
      failureCount++;
    }
  }

  return NextResponse.json(
    success({
      processedAt: new Date().toISOString(),
      totalReceived: queue.length,
      successCount,
      failureCount,
      syncResults: results,
    })
  );
});

export const GET = apiAdapter(async (request: NextRequest) => {
  const context = await resolveAuth(request);
  const uid = context.uid;

  const url = new URL(request.url);
  const lastSyncTimeStr = url.searchParams.get("lastSyncTimestamp");
  const db = await connectDB();

  let deltaFilter: any = { userId: uid };
  if (lastSyncTimeStr) {
    const lastSyncDate = new Date(parseInt(lastSyncTimeStr, 10));
    deltaFilter.syncedAt = { $gt: lastSyncDate };
  }

  const [deltaContacts, deltaLeads] = await Promise.all([
    db.collection("contacts").find(deltaFilter).limit(100).toArray(),
    db.collection("leads").find(deltaFilter).limit(100).toArray(),
  ]);

  return NextResponse.json(
    success({
      serverTime: Date.now(),
      deltas: {
        contacts: deltaContacts,
        leads: deltaLeads,
      },
    })
  );
});
